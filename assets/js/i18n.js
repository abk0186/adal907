  function detectLang() {
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (saved === "kk" || saved === "ru") return saved;
    } catch (e) {}
    var list = [];
    if (Array.isArray(navigator.languages)) {
      for (var i = 0; i < navigator.languages.length; i++) list.push(navigator.languages[i]);
    }
    if (navigator.language) list.push(navigator.language);
    if (navigator.userLanguage) list.push(navigator.userLanguage);
    for (var j = 0; j < list.length; j++) {
      var l = String(list[j] || "").toLowerCase();
      if (l === "kk" || l.indexOf("kk-") === 0) return "kk";
    }
    return "ru";
  }

  function t(key, lang) {
    var entry = I18N[key];
    if (!entry) return "";
    lang = lang || window.ADAL_LANG || "ru";
    return entry[lang] || entry.ru || "";
  }

  function setMeta(selector, value) {
    var el = document.querySelector(selector);
    if (el && value) el.setAttribute("content", value);
  }

  function applyLang(lang, persist) {
    lang = lang === "kk" ? "kk" : "ru";
    if (persist) {
      try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
    }
    document.documentElement.lang = lang;
    document.documentElement.setAttribute("data-lang", lang);
    window.ADAL_LANG = lang;

    var nodes = document.querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var key = el.getAttribute("data-i18n");
      var attr = el.getAttribute("data-i18n-attr");
      var val = t(key, lang);
      if (!val) continue;
      if (attr) el.setAttribute(attr, val);
      else el.textContent = val;
    }

    var title = t("meta.title", lang);
    if (title) document.title = title;
    setMeta('meta[name="description"]', t("meta.description", lang));
    setMeta('meta[property="og:title"]', t("meta.ogTitle", lang));
    setMeta('meta[property="og:description"]', t("meta.ogDescription", lang));
    setMeta('meta[property="og:locale"]', lang === "kk" ? "kk_KZ" : "ru_KZ");
    setMeta('meta[name="twitter:title"]', t("meta.twitterTitle", lang));
    setMeta('meta[name="twitter:description"]', t("meta.twitterDescription", lang));

    var ld = document.querySelector('script[type="application/ld+json"]');
    if (ld) {
      try {
        var data = JSON.parse(ld.textContent);
        data.name = t("ld.name", lang);
        data.description = t("ld.description", lang);
        data.category = t("ld.category", lang);
        ld.textContent = JSON.stringify(data, null, 2);
      } catch (e) {}
    }

    var buttons = document.querySelectorAll("[data-set-lang]");
    for (var b = 0; b < buttons.length; b++) {
      buttons[b].setAttribute("aria-pressed", buttons[b].getAttribute("data-set-lang") === lang ? "true" : "false");
    }

    document.documentElement.classList.add("i18n-ready");
    try {
      document.dispatchEvent(new CustomEvent("adal-lang-change", { detail: { lang: lang } }));
    } catch (e) {}
  }

  function bindSwitch() {
    var buttons = document.querySelectorAll("[data-set-lang]");
    for (var i = 0; i < buttons.length; i++) {
      buttons[i].addEventListener("click", function (event) {
        applyLang(event.currentTarget.getAttribute("data-set-lang"), true);
      });
    }
  }

  function boot() {
    applyLang(detectLang(), false);
    bindSwitch();
  }

  window.ADAL_I18N = I18N;
  window.adalT = t;
  window.adalSetLang = function (lang) { applyLang(lang, true); };
  window.adalDetectLang = detectLang;

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", boot);
  } else {
    boot();
  }
